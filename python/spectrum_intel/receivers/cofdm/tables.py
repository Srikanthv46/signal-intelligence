def prbs(n: int) -> np.ndarray:
    """w_k, k = 0..n-1: X^11 + X^2 + 1, all-ones start (s[n] = s[n-9] ^ s[n-11]): 1111111111100..."""
    s = np.ones(max(n, 11), np.uint8)
    for i in range(11, n):
        s[i] = s[i - 9] ^ s[i - 11]
    return s[:n]


def bch_parity(info53) -> list:
    """14 parity bits of BCH(67,53) for s1..s53 (s1 first = highest power), generator BCH_G."""
    r = 0
    for b in list(info53) + [0] * 14:
        r = (r << 1) | int(b)
        if r & (1 << 14):
            r ^= BCH_G
    return [(r >> (13 - i)) & 1 for i in range(14)]


def bits(v: int, n: int) -> list:
    return [(v >> (n - 1 - i)) & 1 for i in range(n)]
