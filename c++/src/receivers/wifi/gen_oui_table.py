#!/usr/bin/env python3
"""Generate oui_table.cpp: the IEEE MA-L/MA-M/MA-S registry that python mac80211.vendor() reads
from python/spectrum_intel/receivers/wifi/data/oui.tsv.gz, as a compact compiled-in table.

    .venv/bin/python c++/src/receivers/wifi/gen_oui_table.py      (rerun when oui.tsv.gz changes)

The table is read through mac80211._oui_db() itself, so the C++ lookup sees exactly the dict
Python uses (same parsing, same last-wins duplicates). Layout: one sorted key array per prefix
length (6, 7, 9 hex digits) with offsets into a NUL-separated, de-duplicated name pool.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO / "python"))

from spectrum_intel.receivers.wifi import mac80211 as M  # noqa: E402


def c_string(s: bytes) -> str:
    out = []
    for b in s:
        c = chr(b)
        if c in '\\"?':
            out.append("\\" + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return "".join(out)


def main() -> int:
    db = M._oui_db()
    pool, offs = bytearray(), {}
    for v in sorted(set(db.values())):
        offs[v] = len(pool)
        pool += v.encode("utf-8") + b"\0"
    lines = ["// GENERATED by gen_oui_table.py from python/spectrum_intel/receivers/wifi/data/oui.tsv.gz.",
             "// Do not edit. IEEE MA-L/MA-M/MA-S registry (via Wireshark manuf): hex prefix -> vendor.",
             '#include "receivers/wifi/oui_table.hpp"', "", "#include <algorithm>", "",
             "namespace si::rx::wifi::detail {", "namespace {", "",
             "struct Entry {", "  uint64_t key;", "  uint32_t name;", "};", ""]
    lines.append("const char kPool[] =")
    chunk = 2000
    for i in range(0, len(pool), chunk):
        lines.append(f'    "{c_string(bytes(pool[i:i + chunk]))}"')
    lines[-1] += ";"
    lines.append("")
    for n in (6, 7, 9):
        keys = sorted((int(k, 16), offs[v]) for k, v in db.items() if len(k) == n)
        lines.append(f"const Entry kKeys{n}[] = {{")
        row = []
        for k, o in keys:
            row.append(f"{{0x{k:x},{o}}}")
            if len(row) == 8:
                lines.append("    " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ",".join(row) + ",")
        lines.append("};")
        lines.append("")
    lines += [
        "template <size_t N>",
        "const char* find(const Entry (&tab)[N], uint64_t key) {",
        "  auto it = std::lower_bound(std::begin(tab), std::end(tab), key,",
        "                             [](const Entry& e, uint64_t k) { return e.key < k; });",
        "  return (it != std::end(tab) && it->key == key) ? kPool + it->name : nullptr;",
        "}",
        "",
        "}  // namespace",
        "",
        "const char* oui_registry(const std::string& hex_upper) {",
        "  const size_t n = hex_upper.size();",
        "  if (n != 6 && n != 7 && n != 9) return nullptr;",
        "  uint64_t key = 0;",
        "  for (char c : hex_upper) {",
        "    int d = (c >= '0' && c <= '9') ? c - '0' : (c >= 'A' && c <= 'F') ? c - 'A' + 10 : -1;",
        "    if (d < 0) return nullptr;",
        "    key = (key << 4) | static_cast<uint64_t>(d);",
        "  }",
        "  return n == 6 ? find(kKeys6, key) : n == 7 ? find(kKeys7, key) : find(kKeys9, key);",
        "}",
        "",
        f"size_t oui_registry_size() {{ return {len(db)}; }}",
        "",
        "}  // namespace si::rx::wifi::detail",
        ""]
    (HERE / "oui_table.cpp").write_text("\n".join(lines))
    print(f"oui_table.cpp: {len(db)} prefixes, {len(pool)} bytes of names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
