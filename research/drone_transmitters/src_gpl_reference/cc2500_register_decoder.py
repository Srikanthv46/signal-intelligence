F=26e6
def cc(name,f2,f1,f0,m4,m3,m2,m1,m0,dev,pktctrl0=None,sync=None):
    fbase=((f2<<16)|(f1<<8)|f0)*F/2**16
    bw=F/(8*(4+((m4>>4)&3))*2**(m4>>6))
    dr=(256+m3)*2**(m4&15)*F/2**28
    mod={0:'2FSK',1:'GFSK',3:'ASK',7:'MSK'}[(m2>>4)&7]
    sm=m2&7
    pre=[2,3,4,6,8,12,16,24][(m1>>4)&7]
    fec=(m1>>7)&1
    sp=F/2**18*(256+m0)*2**(m1&3)
    d=F/2**17*(8+(dev&7))*2**((dev>>4)&7)
    wh=None if pktctrl0 is None else (pktctrl0>>6)&1
    crc=None if pktctrl0 is None else (pktctrl0>>2)&1
    print(f"{name}: base {fbase/1e6:.4f} MHz, spacing {sp/1e3:.3f} kHz, rate {dr/1e3:.2f} kbps, dev {d/1e3:.2f} kHz, rxBW {bw/1e3:.0f} kHz, {mod}, syncmode {sm}, preamble {pre} B, FEC {fec}, whiten {wh}, crc {crc}, sync {sync}")
